export function dkr(n: number): string {
  return n.toLocaleString("da-DK") + " kr.";
}

/** Fire varer har ingen pris i hans katalog. "0 kr." ville læses som
    gratis, så de får en pris på forespørgsel i stedet. */
export function hasPrice(p: Product): boolean {
  return p.price > 0;
}

/** Et ægte tilbud, ikke bare et flag. */
export function isDeal(p: Product): boolean {
  return p.sale != null && p.sale < p.regular;
}
